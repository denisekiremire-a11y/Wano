/**
 * Generates supabase/migrations/20261116000200_import_wishlist.sql from data/wishlist.ts.
 * The migration is idempotent (ON CONFLICT DO NOTHING keyed on slugs), so re-running it never
 * duplicates or overwrites products the administrator has since edited.
 *
 *   npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  categories,
  retailers,
  gifts,
  PRICES_RECORDED_ON,
  DOC_BUDGET_TOTAL_AED,
  DOC_FULL_TOTAL_AED,
  DOC_TOTALS_NOTE,
} from "../data/wishlist";
import { imageCaptionFor } from "../src/lib/images";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const b = (v: boolean | undefined) => (v ? "true" : "false");

export const WELCOME_TEXT =
  "We’ve put together a little wishlist of things we’re excited to welcome our baby with. If you’d like to contribute, choose something you love from the list. Thank you for being part of this special journey.";
export const PRICE_NOTICE =
  "Prices were recorded in Dubai on 24 October 2026 and may have changed. Please double-check the price with the retailer before buying.";

export function buildSql(): string {
  const out: string[] = [];
  out.push("-- GENERATED by scripts/generate-seed.ts from data/wishlist.ts — do not edit by hand.");
  out.push(`-- Imports all ${gifts.length} options from Baby_List.pdf (${categories.length} categories).`);
  out.push("");
  out.push("insert into public.registry_settings (id, registry_title, welcome_heading, welcome_text, prices_recorded_on, price_notice, doc_budget_total_aed, doc_full_total_aed, doc_totals_note)");
  out.push(
    `values (1, 'Our Baby Registry', 'Made with love for our little one.', ${q(WELCOME_TEXT)}, ${q(PRICES_RECORDED_ON)}, ${q(PRICE_NOTICE)}, ${DOC_BUDGET_TOTAL_AED}, ${DOC_FULL_TOTAL_AED}, ${q(DOC_TOTALS_NOTE)})`,
  );
  out.push("on conflict (id) do nothing;");
  out.push("");

  out.push("insert into public.categories (slug, name, description, sort_order, doc_budget_aed, doc_full_aed) values");
  out.push(
    categories
      .map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${i + 1}, ${c.docBudgetAed}, ${c.docFullAed})`)
      .join(",\n") + "\non conflict (slug) do nothing;",
  );
  out.push("");

  out.push("insert into public.retailers (slug, name, notes) values");
  out.push(retailers.map((r) => `  (${q(r.slug)}, ${q(r.name)}, ${q(r.notes)})`).join(",\n") + "\non conflict (slug) do nothing;");
  out.push("");

  out.push(
    "insert into public.gifts (slug, category_id, name, description, notes, price_aed, sale_price_aed, price_min_aed, price_max_aed, price_unit, price_basis, price_label, tier, in_doc_budget, in_doc_full, is_alternative, is_featured, image_url, image_kind, image_caption, photo_refs, sort_order)",
  );
  out.push("select v.slug, c.id, v.name, v.description, v.notes, v.price_aed, v.sale_price_aed, v.price_min_aed, v.price_max_aed, v.price_unit, v.price_basis::public.price_basis, v.price_label, v.tier::public.gift_tier, v.in_doc_budget, v.in_doc_full, v.is_alternative, v.is_featured, v.image_url, v.image_kind::public.image_kind, v.image_caption, v.photo_refs, v.sort_order");
  out.push("from (values");
  out.push(
    gifts
      .map((g, i) =>
        `  (${[
          q(g.slug), q(g.category), q(g.name), q(g.description), q(g.notes ?? null),
          `${n(g.price)}::numeric`, `${n(g.salePrice)}::numeric`, `${n(g.priceMin)}::numeric`, `${n(g.priceMax)}::numeric`,
          q(g.priceUnit ?? null), q(g.basis), q(g.priceLabel), q(g.tier),
          b(g.inDocBudget), b(g.inDocFull), b(g.isAlternative), b(g.featured),
          q(g.image), q(g.imageKind), q(imageCaptionFor(g.imageKind, g.photoRefs ?? null)), q(g.photoRefs ?? null), (i + 1) * 10,
        ].join(", ")})`,
      )
      .join(",\n"),
  );
  out.push(
    ") as v(slug, category_slug, name, description, notes, price_aed, sale_price_aed, price_min_aed, price_max_aed, price_unit, price_basis, price_label, tier, in_doc_budget, in_doc_full, is_alternative, is_featured, image_url, image_kind, image_caption, photo_refs, sort_order)",
  );
  out.push("join public.categories c on c.slug = v.category_slug");
  out.push("on conflict (slug) do nothing;");
  out.push("");

  const links = gifts.flatMap((g) => g.retailers.map((r) => ({ gift: g.slug, ...r })));
  out.push("insert into public.gift_retailers (gift_id, retailer_id, source_note, is_primary)");
  out.push("select g.id, r.id, v.note, v.is_primary from (values");
  out.push(links.map((l) => `  (${q(l.gift)}, ${q(l.slug)}, ${q(l.note)}, ${b(l.primary)})`).join(",\n"));
  out.push(") as v(gift_slug, retailer_slug, note, is_primary)");
  out.push("join public.gifts g on g.slug = v.gift_slug");
  out.push("join public.retailers r on r.slug = v.retailer_slug");
  out.push("on conflict (gift_id, retailer_id) do nothing;");
  out.push("");
  return out.join("\n");
}

if (process.argv[1]?.endsWith("generate-seed.ts")) {
  const target = join(__dirname, "..", "supabase", "migrations", "20261116000200_import_wishlist.sql");
  writeFileSync(target, buildSql());
  console.log(`Wrote ${target} (${gifts.length} gifts)`);
}
