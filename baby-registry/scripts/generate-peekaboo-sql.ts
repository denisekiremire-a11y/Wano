/**
 * Generates supabase/migrations/20261118000100_peekaboo_uganda.sql from data/peekaboo-products.json:
 * replaces each of the 77 wishlist gifts with its chosen Peekaboo Uganda product (name, UGX price,
 * photo and direct product link), switches the registry to UGX only, and removes the UAE shops.
 *
 * The snapshot was taken from Peekaboo's public catalogue (https://www.peekaboo.ug/products.json)
 * and every product link was opened and returned 200 on the date in the file. Nothing is invented:
 * names, prices, photos and links all come from Peekaboo's own listing.
 *
 *   npx tsx scripts/generate-peekaboo-sql.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Product {
  giftSlug: string;
  slug: string;
  name: string;
  description: string;
  url: string;
  price: number;
  priceMax: number;
  image: string | null;
  inStock: boolean;
  peekabooTitle: string;
}
interface Snapshot {
  source: string;
  checkedOn: string;
  currency: "UGX";
  products: Product[];
}

const q = (v: string | number | null | undefined) =>
  v == null ? "null" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`;

const fmt = new Intl.NumberFormat("en-US");
const dateText = (iso: string) =>
  new Date(`${iso}T12:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

export function loadSnapshot(): Snapshot {
  return JSON.parse(readFileSync(join(__dirname, "..", "data", "peekaboo-products.json"), "utf8")) as Snapshot;
}

export function buildPeekabooSql(s: Snapshot = loadSnapshot()): string {
  const on = dateText(s.checkedOn);
  const rows = s.products.map((p) => {
    const ranged = p.priceMax !== p.price;
    const priceText = ranged ? `UGX ${fmt.format(p.price)}–${fmt.format(p.priceMax)}` : `UGX ${fmt.format(p.price)}`;
    const notes = p.inStock ? null : `Shown as sold out on Peekaboo on ${on} — check with Peekaboo before buying.`;
    return [
      q(p.giftSlug),
      q(p.slug),
      q(p.name),
      q(p.description),
      ranged ? "null" : q(p.price),
      ranged ? q(p.price) : "null",
      ranged ? q(p.priceMax) : "null",
      q(`${priceText} at peekaboo.ug, ${on}`),
      q(notes),
      q(p.image),
      q(p.url),
      q(p.peekabooTitle.slice(0, 300)),
    ];
  });

  const out: string[] = [];
  out.push("-- GENERATED by scripts/generate-peekaboo-sql.ts from data/peekaboo-products.json — do not edit by hand.");
  out.push(`-- Replaces the ${s.products.length} wishlist gifts with products from Peekaboo Uganda (peekaboo.ug),`);
  out.push(`-- priced in UGX as listed on ${on}, and switches the registry to UGX only.`);
  out.push("");
  out.push("-- Safety: a guest's pledge must never silently turn into a different product.");
  out.push("do $$");
  out.push("begin");
  out.push("  if exists (select 1 from public.reservations where status in ('active', 'purchased')) then");
  out.push("    raise exception 'Some gifts are still reserved or purchased. Release or cancel them in Admin → Reservations first, then run this again.';");
  out.push("  end if;");
  out.push("end $$;");
  out.push("");
  out.push("-- The new shop.");
  out.push("insert into public.retailers (slug, name, website_url, search_url_template, notes) values");
  out.push(
    "  ('peekaboo-ug', 'Peekaboo Uganda', 'https://www.peekaboo.ug/', 'https://www.peekaboo.ug/search?q={q}', 'Ugandan baby store, online at peekaboo.ug. Prices in UGX.')",
  );
  out.push("on conflict (slug) do update set name = excluded.name, website_url = excluded.website_url,");
  out.push("  search_url_template = excluded.search_url_template, notes = excluded.notes;");
  out.push("");
  out.push("-- Each gift becomes its Peekaboo product (matched by its original slug). Prices are UGX:");
  out.push("-- the *_aed columns keep their historical names but now hold amounts in UGX.");
  out.push("select set_config('registry.allow_status_change', 'on', true);");
  out.push("with v(old_slug, new_slug, name, description, price, price_min, price_max, price_label, notes, image_url, url, product_note) as (values");
  out.push(rows.map((r) => `  (${r.join(", ")})`).join(",\n"));
  out.push(")");
  out.push("update public.gifts g set");
  out.push("  slug = v.new_slug, name = v.name, description = v.description, notes = v.notes,");
  out.push("  price_aed = v.price::numeric, sale_price_aed = null, price_min_aed = v.price_min::numeric, price_max_aed = v.price_max::numeric,");
  out.push("  price_unit = null, price_basis = 'online', price_label = v.price_label,");
  out.push("  image_url = v.image_url, image_kind = 'uploaded', image_caption = 'Product photo from Peekaboo Uganda', photo_refs = null,");
  out.push("  status = 'available', status_changed_at = now()");
  out.push("from v where g.slug = v.old_slug;");
  out.push("select set_config('registry.allow_status_change', 'off', true);");
  out.push("");
  out.push("-- One direct, checked Peekaboo link per gift; the UAE shops go.");
  out.push("delete from public.gift_retailers gr using public.retailers r where gr.retailer_id = r.id and r.slug <> 'peekaboo-ug';");
  out.push("with v(slug, url, note) as (values");
  out.push(s.products.map((p) => `  (${q(p.slug)}, ${q(p.url)}, ${q(p.peekabooTitle.slice(0, 300))})`).join(",\n"));
  out.push(")");
  out.push("insert into public.gift_retailers (gift_id, retailer_id, product_url, url_verified, product_note, is_primary)");
  out.push("select g.id, r.id, v.url, true, v.note, true");
  out.push("from v join public.gifts g on g.slug = v.slug join public.retailers r on r.slug = 'peekaboo-ug'");
  out.push("on conflict (gift_id, retailer_id) do update set product_url = excluded.product_url, url_verified = true,");
  out.push("  product_note = excluded.product_note, is_primary = true;");
  out.push("delete from public.retailers where slug in ('mom-store', 'carters', 'mamas-and-papas', 'mumzworld', 'carrefour-uae', 'centrepoint');");
  out.push("");
  out.push("-- Category notes described the Dubai shops; replace them.");
  out.push("update public.categories c set description = v.d from (values");
  out.push(
    [
      ["travel", "Two routes: the Pibi 4-in-1 is car seat and stroller in one, or pick a car seat and a separate stroller."],
      ["sleep-and-nursery", null],
      ["clothing", null],
      ["extras-and-inspiration", "Extras from the original inspiration pictures, matched to Peekaboo products."],
    ]
      .map(([slug, d]) => `  (${q(slug)}, ${d == null ? "null::text" : q(d)})`)
      .join(",\n"),
  );
  out.push(") as v(slug, d) where c.slug = v.slug;");
  out.push("");
  out.push("-- UGX only: no exchange rate, no AED document totals.");
  out.push("update public.registry_settings set");
  out.push("  aed_to_ugx_rate = null, rate_updated_at = null, rate_source = null,");
  out.push("  doc_budget_total_aed = null, doc_full_total_aed = null, doc_totals_note = null,");
  out.push(`  prices_recorded_on = ${q(s.checkedOn)},`);
  out.push(
    `  price_notice = ${q(`Prices are from Peekaboo Uganda's website on ${on} and may have changed. Please check on peekaboo.ug before buying.`)}`,
  );
  out.push("where id = 1;");
  out.push("");
  return out.join("\n");
}

if (require.main === module) {
  const file = join(__dirname, "..", "supabase", "migrations", "20261118000100_peekaboo_uganda.sql");
  writeFileSync(file, buildPeekabooSql());
  console.log(`✔ wrote ${file}`);
}
