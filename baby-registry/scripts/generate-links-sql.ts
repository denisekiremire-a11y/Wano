/**
 * Generates supabase/migrations/20261117000200_product_links_and_peaches.sql from
 * data/product-links.ts. Idempotent, and never overwrites a product link the family has already
 * set in the admin (only fills links that are still empty).
 *
 *   npx tsx scripts/generate-links-sql.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { productLinks, retailerExtras } from "../data/product-links";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);

export const PEACHES_TITLE = "Baby Peaches";
export const PEACHES_HEADING = "Made with love for little Peaches.";

export function buildLinksSql(): string {
  const out: string[] = [];
  out.push("-- GENERATED by scripts/generate-links-sql.ts from data/product-links.ts — do not edit by hand.");
  out.push(`-- ${productLinks.length} direct product links (${productLinks.filter((l) => l.verified).length} opened and checked), retailer search pages, and the "Peaches" registry name.`);
  out.push("");
  out.push("alter table public.retailers add column if not exists search_url_template text");
  out.push("  check (search_url_template is null or (search_url_template ~* '^https://' and position('{q}' in search_url_template) > 0));");
  out.push("alter table public.gift_retailers add column if not exists product_note text check (char_length(product_note) <= 300);");
  out.push("");
  out.push("insert into public.retailers (slug, name, website_url, search_url_template, notes) values");
  out.push(
    retailerExtras.map((r) => `  (${q(r.slug)}, ${q(r.name)}, ${q(r.websiteUrl)}, ${q(r.searchUrlTemplate)}, ${q(r.notes || null)})`).join(",\n") +
      "\non conflict (slug) do update set",
  );
  out.push("  website_url = coalesce(public.retailers.website_url, excluded.website_url),");
  out.push("  search_url_template = coalesce(public.retailers.search_url_template, excluded.search_url_template),");
  out.push("  notes = coalesce(nullif(public.retailers.notes, ''), excluded.notes);");
  out.push("");
  const values = productLinks
    .map((l) => `  (${q(l.gift)}, ${q(l.retailer)}, ${q(l.url)}, ${l.verified}, ${q(l.note)})`)
    .join(",\n");
  out.push("with v(gift_slug, retailer_slug, url, verified, note) as (values");
  out.push(values);
  out.push(")");
  out.push("insert into public.gift_retailers (gift_id, retailer_id, product_url, url_verified, product_note, is_primary)");
  out.push("select g.id, r.id, v.url, v.verified, v.note, true");
  out.push("  from v join public.gifts g on g.slug = v.gift_slug join public.retailers r on r.slug = v.retailer_slug");
  out.push("on conflict (gift_id, retailer_id) do update set");
  out.push("  product_url = excluded.product_url, url_verified = excluded.url_verified,");
  out.push("  product_note = excluded.product_note, is_primary = true");
  out.push("  where public.gift_retailers.product_url is null;");
  out.push("");
  out.push("-- The retailer with the direct link becomes the gift's primary shop.");
  out.push("update public.gift_retailers gr set is_primary = false");
  out.push("  from public.gift_retailers linked");
  out.push(" where linked.gift_id = gr.gift_id and linked.id <> gr.id");
  out.push("   and linked.product_url is not null and gr.product_url is null and gr.is_primary;");
  out.push("");
  out.push("-- The baby's nickname. Only replaces the original defaults, never text the family has edited.");
  out.push(`update public.registry_settings set registry_title = ${q(PEACHES_TITLE)} where id = 1 and registry_title = 'Our Baby Registry';`);
  out.push(`update public.registry_settings set welcome_heading = ${q(PEACHES_HEADING)} where id = 1 and welcome_heading = 'Made with love for our little one.';`);
  out.push("");
  return out.join("\n");
}

if (process.argv[1]?.endsWith("generate-links-sql.ts")) {
  const target = join(__dirname, "..", "supabase", "migrations", "20261117000200_product_links_and_peaches.sql");
  writeFileSync(target, buildLinksSql());
  console.log(`Wrote ${target} (${productLinks.length} links)`);
}
